/* Writes src/data/asset-manifest.ts: every picture in src/assets, found by its plain path ("assets/cars/svj.webp").
   The database keeps those plain paths for the pictures that ship with the site; the build gives each file its own
   cache-safe address. Run `npm run assets` after adding or removing a picture (`npm run build` does it too). */
import { readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const DIR = join(ROOT, 'src/assets');
const IMAGE = /\.(webp|jpe?g|png|avif)$/i;

const files = [];
(function walk(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (IMAGE.test(e.name)) files.push(relative(join(ROOT, 'src'), p).replace(/\\/g, '/'));
  }
})(DIR);
files.sort();

const lines = [
  '/* Generated by scripts/assets-manifest.mjs: every picture in src/assets by its plain path. Do not edit.',
  '   Server only: the pictures are imported here so the build fingerprints them, and pages pass plain addresses',
  '   to the browser (importing this into browser code would ship every picture\'s details with it). */',
  "import 'server-only';",
  ...files.map((f, i) => `import a${i} from '../${f}';`),
  '',
  'export const ASSETS: Record<string, string> = {',
  ...files.map((f, i) => `  '${f}': a${i}.src,`),
  '};',
  '',
];
writeFileSync(join(ROOT, 'src/data/asset-manifest.ts'), lines.join('\n'));
console.log(`assets-manifest: ${files.length} pictures`);
