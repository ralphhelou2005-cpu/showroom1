/* Writes public/engine/home.js: the walk-in engine (src/lib/home.ts) as a small script of its own, which the home page
   starts as soon as its HTML has arrived, without waiting for the rest of the site's code. The film is downloading
   from the first moment (a preload), so the walk-in is ready as soon as its first frames are in.
   React adopts the running engine when it takes over the page (src/components/HomeEngine.tsx), and starts its own
   copy after a page change inside the site. Run by `npm run dev` and `npm run build`. */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const TMP = join(ROOT, 'node_modules/.cache/milcar-engine');
rmSync(TMP, { recursive: true, force: true });
execFileSync(process.execPath, [join(ROOT, 'node_modules/typescript/bin/tsc'), join(ROOT, 'src/lib/home.ts'), '--ignoreConfig',
  '--outDir', TMP, '--target', 'es2022', '--module', 'esnext', '--skipLibCheck', '--lib', 'es2023,dom,dom.iterable', '--removeComments'], { stdio: 'inherit' });

const code = readFileSync(join(TMP, 'home.js'), 'utf8');
if (!/^export function startHome\(/m.test(code) || /^\s*(import|export)\s(?!function startHome)/m.test(code)) {
  throw new Error('build-engine: src/lib/home.ts must stay self-contained, with startHome as its only export');
}
const out = `/* Generated by scripts/build-engine.mjs from src/lib/home.ts. Do not edit. */
(() => {
${code.replace(/^export function startHome\(/m, 'function startHome(')}
const main = document.getElementById('main');
if (main && document.getElementById('stage') && !window.__milcarHome) window.__milcarHome = { stop: startHome(main), owner: 'page' };
})();
`;
mkdirSync(join(ROOT, 'public/engine'), { recursive: true });
writeFileSync(join(ROOT, 'public/engine/home.js'), out);
console.log(`build-engine: public/engine/home.js (${Math.round(out.length / 1024)} KB)`);
